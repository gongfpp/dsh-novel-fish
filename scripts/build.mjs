import { build } from 'esbuild'
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, resolve, join } from 'node:path'
import { createRequire } from 'node:module'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const output = resolve(root, 'lib/client.js')
await mkdir(dirname(output), { recursive: true })
const result = await build({
  absWorkingDir: root,
  entryPoints: [resolve(root, 'src/client.js')],
  bundle: true,
  platform: 'browser',
  format: 'iife',
  target: ['chrome120'],
  outfile: output,
  sourcemap: false,
  metafile: true,
  legalComments: 'eof',
  logLevel: 'info',
  define: { 'process.env.NODE_ENV': '"production"' },
})
await writeFile(output, (await readFile(output, 'utf8')).replace(/[\t ]+$/gmu, ''))

const packages = new Map()
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.includes('node_modules/')) continue
  let directory = dirname(resolve(root, input))
  while (directory.startsWith(join(root, 'node_modules'))) {
    const files = await readdir(directory)
    if (files.includes('package.json')) {
      const manifest = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'))
      const key = `${manifest.name}@${manifest.version}`
      if (!packages.has(key)) {
        const licenses = files.filter(name => /^(?:licen[cs]e|copying)(?:[.-]|$)/iu.test(name))
        const text = licenses.length
          ? (await Promise.all(licenses.map(name => readFile(join(directory, name), 'utf8')))).join('\n\n')
          : await readFile(join(root, 'scripts/licenses', `${manifest.name}.txt`), 'utf8')
        packages.set(key, `${key}\nLicense declaration: ${JSON.stringify(manifest.license)}\n\n${text.trim().replace(/[\t ]+$/gmu, '')}`)
      }
      break
    }
    directory = dirname(directory)
  }
}
// JSZip's browser entry is prebundled: esbuild cannot see its nested libraries.
// Keep their original notices as well; do not mistake metafile inputs for the full license graph.
const require = createRequire(import.meta.url)
const zipRequire = createRequire(require.resolve('jszip/package.json'))
const lieRequire = createRequire(zipRequire.resolve('lie/package.json'))
for (const manifestPath of [
  zipRequire.resolve('pako/package.json'),
  zipRequire.resolve('lie/package.json'),
  zipRequire.resolve('setimmediate/package.json'),
  lieRequire.resolve('immediate/package.json'),
]) {
  const directory = dirname(manifestPath)
  const manifest = JSON.parse(await readFile(manifestPath, 'utf8'))
  const names = (await readdir(directory)).filter(name => /^(?:licen[cs]e|copying)(?:[.-]|$)/iu.test(name))
  if (!names.length) throw new Error(`Missing bundled license: ${manifest.name}`)
  const texts = await Promise.all(names.map(name => readFile(join(directory, name), 'utf8')))
  if (manifest.name === 'pako') texts.push(await readFile(join(directory, 'lib/zlib/README'), 'utf8'))
  const key = `${manifest.name}@${manifest.version}`
  packages.set(key, `${key}\nBundled inside JSZip's browser distribution.\nLicense declaration: ${JSON.stringify(manifest.license)}\n\n${texts.join('\n\n').trim().replace(/[\t ]+$/gmu, '')}`)
}
const notices = ['Bundled browser dependencies (generated by scripts/build.mjs).', ...[...packages].sort(([a], [b]) => a.localeCompare(b)).map(([, text]) => text)]
await writeFile(join(root, 'THIRD-PARTY-NOTICES.txt'), `${notices.join('\n\n' + '='.repeat(72) + '\n\n')}\n`)
console.log(`Bundled licenses: ${packages.size}`)
